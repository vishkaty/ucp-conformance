# ── site_claims KI-### projection ────────────────────────────────────────────
def claim_rows(doc):
    rows = sorted(doc["issues"], key=lambda r: r["id"])
    out = []
    for r in rows:
        cuts = "; ".join(f"{c['cut']}: {c['status']}" + (f" ({c['evidence']})" if c.get("evidence") else "")
                         for c in r["status_by_cut"])
        filed = ", ".join(r.get("filed") or []) or "not yet filed"
        out.append({
            "id": r["id"],
            "text": r["symptom"],
            "page": PAGE_KEY,
            "class": "REG",
            "evidence": (f"repro: {r['repro']['command']} -> expected: {r['repro']['expected']}; observed: "
                         f"{r['repro']['observed']}. status: {cuts}. filed: {filed}. ledger row "
                         f"{r['ledger_row']} (ops/GAP-LEDGER-0825.md), origin {r['origin']}, confidence "
                         f"{r['confidence']}, re-verified {r['re_verified']}; row validated by the run_suite "
                         f"'known-issues' gate; this claim is GENERATED by conformance/web/gen_known_issues.py "
                         f"from conformance/ci/known_issues.json"),
            "added": doc["generated"],
            "review_by": r["review_by"],
        })
    return out


def claims_synced(claims_doc, doc):
    """The claims register with its KI-### rows replaced by the projection (other rows untouched)."""
    out = json.loads(json.dumps(claims_doc))
    kept = [c for c in out.get("claims", []) if not (isinstance(c.get("id"), str) and c["id"].startswith("KI-"))]
    out["claims"] = kept + claim_rows(doc)
    return out


def _claims_serialize(doc):
    sync = _load_module("sync_site_claims", ROOT / "conformance" / "web" / "sync_site_claims.py")
    return sync.serialize(doc)


def targets(doc):
    """{relative path under public/: expected bytes} for the three projections."""
    claims_path = PUB / CLAIMS_NAME
    claims_doc = json.load(open(claims_path, encoding="utf-8")) if claims_path.exists() else {"claims": []}
    return {
        JSON_NAME: render_json(doc),
        HTML_NAME: render_html(doc),
        CLAIMS_NAME: _claims_serialize(claims_synced(claims_doc, doc)),
    }


def check_failures(today=None):
    """Failure strings (empty = in sync). Validator findings come first and stop the compare."""
    doc, vfails = load_source(today)
    if vfails:
        return [f"validator: {f}" for f in vfails] + ["refusing to render from a document the validator rejects"]
    fails = []
    for rel, want in targets(doc).items():
        f = PUB / rel
        if not f.exists():
            fails.append(f"public/{rel} missing — run gen_known_issues.py --write")
        elif f.read_text(encoding="utf-8") != want:
            fails.append(f"public/{rel} differs from regeneration (hand-edited or stale) — run gen_known_issues.py --write")
    return fails


def _stale(doc, today):
    n = 0
    for r in doc.get("issues") or []:
        try:
            n += (today - datetime.date.fromisoformat(r["re_verified"])).days > 30
        except (KeyError, ValueError):
            n += 1
    return n


def main(argv=None):
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    today = datetime.date.today()
    doc, vfails = load_source(today)
    rows = doc.get("issues") or []
    head = (f"known-issues page: {len(rows)} rows · "
            f"{sum(1 for r in rows if r.get('refuted') is not False)} refuted · {_stale(doc, today)} stale · "
            f"{'schema OK' if not vfails else 'schema RED'}")
    if vfails:
        for f in vfails:
            print(f"  x {f}")
        print(f"{head} · REFUSED — nothing rendered from a document the validator rejects")
        return 1
    if args.write:
        PUB.mkdir(parents=True, exist_ok=True)
        for rel, content in targets(doc).items():
            (PUB / rel).write_text(content, encoding="utf-8")
        print(f"{head} · wrote public/{JSON_NAME}, public/{HTML_NAME}, KI-* claims in public/{CLAIMS_NAME}")
        return 0
    fails = check_failures(today)
    for f in fails:
        print(f"  x {f}")
    print(f"{head} · " + (f"public/{JSON_NAME}, public/{HTML_NAME}, site_claims KI-* in sync" if not fails
                          else f"OUT OF SYNC ({len(fails)} target(s))"))
    return 0 if not fails else 1


if __name__ == "__main__":
    sys.exit(main())
