#!/usr/bin/env python3
"""
gen_known_issues.py — the KNOWN ISSUES page is a PROJECTION of one file (SITE-R-033, D5-12,
PLAN-v3 §2.13): conformance/ci/known_issues.json (validated by validate_known_issues.py) is the
only source of

    public/known-issues.json     rows + recomputed summary counts (the tracker binds to these)
    public/known-issues.html     one card per row, id="KI-###", symptom verbatim, repro, per-cut status
    site_claims.json KI-###      one REG claim per row (text = symptom, review_by = the row's clock)

Deterministic by construction: sorted iteration, no timestamps beyond the source's own
`generated` date, content derived only from the source. The validator runs FIRST and a red
validator (a refuted row, a stale re_verified, an unevidenced `fixed`, …) refuses to render
anything. `--check` regenerates into memory and byte-compares all three targets (site_gates.py
checkdocs, deploy.sh step 2 and the run_suite gate `known-issues-page` call it).

    python3 conformance/web/gen_known_issues.py --write    # (re)write the three targets
    python3 conformance/web/gen_known_issues.py --check    # `N rows · 0 refuted · 0 stale · schema OK · … in sync`
SPCK_PUBLIC points both modes at a scratch copy of public/. Stdlib only.
"""
import argparse
import collections
