#!/usr/bin/env python3
"""
run_compare.py — P2-13: FAIR, reproducible kill-rate comparison of the spck
conformance suite vs the OFFICIAL UCP conformance suite, on a COMMON mutant set.

What it proves (and only this): for each injected MUST-defect in mutants.json —
defects a conformant server would never emit, injected by sticky_proxy.py in
front of the pinned flower golden — does each suite, run exactly as a merchant
would run it, AFFIRMATIVELY report the server non-conformant?

Fairness rules (enforced here, not just promised):
  * Both suites talk to the SAME mutated server (same proxy URL, same defect,
    no cooperation headers). Baselines run through the same proxy in
    passthrough mode, so the network path is identical in every condition.
  * EVERY suite run gets a freshly booted, freshly reseeded golden (identical
    pinned seed state). Not a convenience: the flower reference DEPLETES
    INVENTORY on every completed checkout, so a long-lived golden eventually
    answers every create with 400 OUT_OF_STOCK and mass-fails whichever suite
    runs later — and even short of exhaustion, a shared long-lived server
    means the second suite always faces a more-depleted state than the first.
    A fresh golden per suite run removes the whole class.
  * The official suite runs AS-CONFIGURED by its own repo (its flower-shop
    conformance_input + fixtures, full `pytest` run — never a filtered subset).
    Our suite runs AS-SHIPPED (merchant.py) with our canonical flower config
    (REF_CONFIG from validate_merchant_checks.py) — no comparison-specific
    checks, no comparison-specific config.
  * CATCH is symmetric and strict: the suite's own normal report must signal
    non-conformance —
      official: >=1 test newly failing/erroring vs its clean-golden baseline
                (tests unstable across baseline runs are excluded from
                catch credit entirely);
      spck:     >=1 MUST reported as a deviation (aggregate goes red). A run
                that merely degrades to not-tested/incomplete is a MISS for us.
      A harness/runner crash is NEVER a catch — it is flagged for review.
  * Only `shared_surface: true` mutants enter the head-to-head. Mutants on
    surfaces the official suite does not attempt are reported separately and
    never blended into the headline numbers.
  * Determinism: every mutant is run --repeat times (default 2) for each suite;
    a mutant only counts as CAUGHT by a suite if EVERY repeat catches it, and
    disagreement is flagged in the results.

Usage (see README.md for the full reproduction script):
    python3 run_compare.py [--golden-port 8290] [--proxy-port 8291]
        [--repeat 2] [--only id1,id2] [--out results/]
Exit 0 = comparison completed (whatever the numbers say); nonzero = harness error.
"""
import argparse, json, os, pathlib, re, shutil, socket, subprocess, sys, tempfile, time
import urllib.request
try:                                   # junit files here are locally generated by
    import defusedxml.ElementTree as ET     # pytest, but parse defensively anyway
except ImportError:                    # (defusedxml is optional; stdlib fallback)
    import xml.etree.ElementTree as ET

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
SELF = ROOT / "conformance" / "selfcheck"
CHECKS = ROOT / "conformance" / "checks"
OFFICIAL_DIR = HERE / ".official" / "conformance"
PYSDK_DIR = HERE / ".official" / "python-sdk"


