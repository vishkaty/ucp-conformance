def _port_free(port):
    with socket.socket() as s:
        return s.connect_ex(("127.0.0.1", port)) != 0


class Golden:
    """Boots a FRESH pinned golden (reseeded to the identical initial state)
    before every suite run — see the fairness rules in the module docstring."""

    def __init__(self, port, sim_secret, db_dir):
        self.port, self.sim_secret, self.db_dir = port, sim_secret, db_dir
        self.url = f"http://localhost:{port}"

    def boot(self):
        # Wipe the databases so "identical pinned seed state" is literally true:
        # import_csv reseeds products/inventory/discounts, but checkout-session
        # and order rows in transactions.db would otherwise survive across boots.
        for db in pathlib.Path(self.db_dir).glob("*.db"):
            db.unlink(missing_ok=True)
        env = dict(os.environ, PORT=str(self.port), SIM_SECRET=self.sim_secret,
                   DB_DIR=self.db_dir)
        r = subprocess.run([str(ROOT / "conformance" / "ci" / "serve_golden.sh")],
                           env=env, capture_output=True, text=True, timeout=300)
        if r.returncode != 0:
            raise RuntimeError(f"golden boot failed:\n{(r.stderr or '')[-1500:]}")

    def stop(self):
        env = dict(os.environ, PORT=str(self.port), DB_DIR=self.db_dir)
        subprocess.run([str(ROOT / "conformance" / "ci" / "stop_golden.sh")],
                       env=env, capture_output=True, text=True, timeout=120)


def start_proxy(golden, port, mutant=None):
    args = [sys.executable, str(HERE / "sticky_proxy.py"),
            "--upstream", golden, "--port", str(port),
            "--rewrite", f"{golden}=http://localhost:{port}"]
    if mutant:
        args += ["--mutate", mutant["mutate"],
                 "--match-path", mutant["match"]["path"],
                 "--match-methods", mutant["match"].get("methods", "GET,POST,PUT,DELETE,PATCH"),
                 "--match-status", mutant["match"].get("status", "all")]
    p = subprocess.Popen(args, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    for _ in range(50):
        try:
            with urllib.request.urlopen(f"http://localhost:{port}/.well-known/ucp", timeout=2):
                return p
        except Exception:
            time.sleep(0.2)
    p.kill()
    raise RuntimeError(f"sticky proxy failed to become ready on :{port}")


def run_spck(server, config_path):
    """Run our as-shipped merchant runner; return (deviating_check_ids, meta).

    The ARBITER is the suite's own verdict gate: rep['verdict']['deviations']
    is the gate's MUST-deviation count (SHOULD/MAY advisories never reach it),
    and the stated catch rule is ">=1 MUST reported as a deviation — the gate's
    red". So: if the gate counts zero MUST deviations, nothing here is a catch,
    no matter which advisory checks flagged; if it counts >0, the deviating
    check ids are the evidence list. No re-derivation of keywords here — the
    gate already did that arbitration, identically for every merchant."""
    r = subprocess.run(
        [sys.executable, str(CHECKS / "merchant.py"), "--server", server,
         "--config", str(config_path), "--json"],
        capture_output=True, text=True, timeout=600)
    if r.returncode not in (0, 2):
        return None, {"crashed": True, "stderr": r.stderr[-2000:]}
    try:
        rep = json.loads(r.stdout)
    except json.JSONDecodeError:
        return None, {"crashed": True, "stderr": "unparseable runner output"}

    flagged = sorted(c["id"] for c in rep["checks"] if c["status"] == "deviation")
    devs = flagged if rep["verdict"]["deviations"] > 0 else []
    meta = {"crashed": False, "aggregate": rep["verdict"]["aggregate"],
            "deviation_musts": rep["verdict"]["deviations"],
            "musts_passed": rep["verdict"]["musts_passed"],
            "advisory_flags": [] if devs else flagged,
            "dev_req_ids": sorted({rid for c in rep["checks"]
                                   if c["status"] == "deviation" for rid in c["req_ids"]})}
    return devs, meta


def run_official(server, sim_secret):
    """Run the official suite exactly as its README prescribes (full pytest run)."""
    with tempfile.NamedTemporaryFile(suffix=".xml", delete=False) as tf:
        junit = tf.name
    env = dict(os.environ, SERVER_URL=server, SIMULATION_SECRET=sim_secret)
    r = subprocess.run(["uv", "run", "pytest", "-q", "--junitxml", junit],
                       cwd=OFFICIAL_DIR, env=env, capture_output=True, text=True,
                       timeout=1800)
    failed, counts = [], {"tests": 0, "failures": 0, "errors": 0, "skipped": 0}
    try:
        root = ET.parse(junit).getroot()
        for suite in root.iter("testsuite"):
            for k in counts:
                counts[k] += int(suite.get(k, 0) or 0)
        for tc in root.iter("testcase"):
            if tc.find("failure") is not None or tc.find("error") is not None:
                failed.append(f"{tc.get('classname')}.{tc.get('name')}")
    except (ET.ParseError, FileNotFoundError):
        return None, {"crashed": True, "stderr": r.stderr[-2000:] + r.stdout[-2000:]}
    finally:
        pathlib.Path(junit).unlink(missing_ok=True)
    crashed = counts["tests"] == 0    # collection error / no tests ran = harness problem
    return (None if crashed else sorted(failed)), {"crashed": crashed, **counts}


