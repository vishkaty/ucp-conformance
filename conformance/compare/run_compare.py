def decide_catch_official(baseline_unstable, baseline_failed, run_failed, crashed):
    """Newly failing/erroring tests, minus anything unstable on the clean golden."""
    if crashed:
        return False, []
    new = sorted((set(run_failed) - set(baseline_failed)) - set(baseline_unstable))
    return bool(new), new


def decide_catch_spck(baseline_deviations, run_deviations, crashed):
    """>=1 MUST deviation the clean-golden baseline did not have."""
    if crashed:
        return False, []
    new = sorted(set(run_deviations) - set(baseline_deviations))
    return bool(new), new


def compute_rates(mutants, records):
    """records: {mutant_id: {"spck_catch": bool, "official_catch": bool}}.
    Head-to-head covers ONLY shared_surface mutants. Non-shared mutants go to
    the addendum. `diagnostic: true` mutants are counted NOWHERE — they are
    measured purely for transparency (e.g. defects excluded from the common
    set because the violated requirement binds the platform, not the server)."""
    mutants = [m for m in mutants if not m.get("diagnostic")]
    shared = [m for m in mutants if m.get("shared_surface")]
    only = [m for m in mutants if not m.get("shared_surface")]
    out = {
        "shared_surface": {
            "n": len(shared),
            "spck_caught": sum(1 for m in shared if records[m["id"]]["spck_catch"]),
            "official_caught": sum(1 for m in shared if records[m["id"]]["official_catch"]),
        },
        "spck_only_surface": {
            "n": len(only),
            "spck_caught": sum(1 for m in only if records[m["id"]]["spck_catch"]),
            "official_caught": sum(1 for m in only if records[m["id"]]["official_catch"]),
        },
    }
    for k in out:
        n = out[k]["n"]
        out[k]["spck_rate"] = round(out[k]["spck_caught"] / n, 4) if n else None
        out[k]["official_rate"] = round(out[k]["official_caught"] / n, 4) if n else None
    return out


def validate_citations(mutants, register_dir):
    """Every cited requirement id must exist in the pinned register as MUST/MUST NOT."""
    rows = {}
    for f in sorted(pathlib.Path(register_dir).glob("*.json")):
        d = json.loads(f.read_text())
        items = d if isinstance(d, list) else d.get("requirements", d.get("rows", []))
        for r in items:
            rows[r["id"]] = r
    problems = []
    for m in mutants:
        for cid in m["citations"]:
            r = rows.get(cid)
            if r is None:
                problems.append(f"{m['id']}: cites {cid} which is not in the register")
            elif (r.get("keyword") not in ("MUST", "MUST NOT", "REQUIRED")
                  and not m.get("diagnostic")):
                # diagnostic mutants exist precisely because their citation is
                # NOT a server MUST (platform-binding / MAY); everything that
                # counts anywhere must cite a MUST.
                problems.append(f"{m['id']}: cites {cid} which is {r.get('keyword')}, not a MUST")
    return problems, rows


