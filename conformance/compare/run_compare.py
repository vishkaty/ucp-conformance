def render_md(results):
    m = results
    L = []
    L.append("# Kill-rate comparison — spck suite vs official UCP conformance suite\n")
    L.append(f"_Generated {m['meta']['timestamp']} · methodology + fairness rules: "
             f"see README.md in this directory. All numbers reproducible via "
             f"`reproduce.sh`._\n")
    L.append("## Pinned inputs\n")
    for k, v in m["meta"]["pins"].items():
        L.append(f"- **{k}**: `{v}`")
    b = m["baseline"]
    L.append("\n## Clean-golden baselines (through the same passthrough proxy)\n")
    L.append(f"- official: {b['official']['tests']} tests, "
             f"{b['official']['failures']} failed, {b['official']['errors']} errors, "
             f"{b['official']['skipped']} skipped"
             + (f" — unstable across baseline runs (excluded from catch credit): "
                f"{', '.join(b['official_unstable'])}" if b["official_unstable"] else
                " — stable across repeat baseline runs"))
    L.append(f"- spck: aggregate `{b['spck']['aggregate']}`, "
             f"{b['spck']['musts_passed']} applicable MUSTs clean-pass, "
             f"{b['spck']['deviation_musts']} deviations\n")
    L.append("## Per-mutant results (head-to-head = shared surface only)\n")
    L.append("| mutant | injected MUST-defect | spec MUST | shared? | spck | official | deterministic |")
    L.append("|---|---|---|---|---|---|---|")
    for r in m["mutants"]:
        spck = "**CATCH** — " + ", ".join(r["spck_new_deviations"][:4]) if r["spck_catch"] \
            else ("crash (not counted)" if r.get("spck_crashed") else "MISS")
        off = "**CATCH** — " + ", ".join(t.split(".")[-1] for t in r["official_new_failures"][:4]) \
            if r["official_catch"] else ("crash (not counted)" if r.get("official_crashed") else "MISS")
        det = "yes" if r["deterministic"] else "**NO — flagged**"
        surf = ("diagnostic — counted nowhere" if r.get("diagnostic")
                else ("Y" if r["shared_surface"] else "N — addendum"))
        L.append(f"| {r['id']} | {r['defect']} | {', '.join(r['citations'])} | "
                 f"{surf} | {spck} | {off} | {det} |")
    rt = m["rates"]["shared_surface"]
    L.append("\n## Head-to-head catch-rate (shared surface only)\n")
    L.append(f"- **spck suite: {rt['spck_caught']}/{rt['n']} "
             f"({round(100 * rt['spck_rate'])}%)**")
    L.append(f"- **official suite: {rt['official_caught']}/{rt['n']} "
             f"({round(100 * rt['official_rate'])}%)**")
    ro = m["rates"]["spck_only_surface"]
    L.append("\n## Addendum — surfaces only spck covers (NEVER counted in the head-to-head)\n")
    L.append(f"- {ro['spck_caught']}/{ro['n']} caught by spck; the official suite does not "
             f"attempt these surfaces, so no official number is claimed for them.")
    for r in m["mutants"]:
        if not r["shared_surface"] and not r.get("diagnostic"):
            L.append(f"  - {r['id']}: {r['defect']} ({', '.join(r['citations'])}) — "
                     f"{'caught' if r['spck_catch'] else 'MISSED'} by spck. "
                     f"{r.get('surface_note', '')}")
    diags = [r for r in m["mutants"] if r.get("diagnostic")]
    if diags:
        L.append("\n## Diagnostics — measured for transparency, counted NOWHERE\n")
        L.append("These defects were excluded from the common set because the "
                 "violated requirement binds the PLATFORM, not the server, in the "
                 "pinned register — but a skeptic deserves the measured outcome:")
        for r in diags:
            s = "CATCH" if r["spck_catch"] else \
                "no red (as the register prescribes: advisory at most)"
            o = "CATCH" if r["official_catch"] else "MISS"
            L.append(f"  - {r['id']}: {r['defect']} ({', '.join(r['citations'])}) — "
                     f"spck {s}, official {o}. {r.get('surface_note', '')}")
    misses = [r for r in m["mutants"] if r["shared_surface"] and not r["spck_catch"]]
    if misses:
        L.append("\n## Where WE missed (gaps in the spck suite — to fix)\n")
        for r in misses:
            L.append(f"- {r['id']}: {r['defect']} — "
                     + ("caught by the official suite; " if r["official_catch"] else "")
                     + "tracked as a spck-suite gap.")
    om = [r for r in m["mutants"] if r["shared_surface"] and not r["official_catch"]]
    if om:
        L.append("\n## Official-suite misses on the common set (candidate upstream test-gap filings)\n")
        for r in om:
            L.append(f"- {r['id']}: {r['defect']} ({', '.join(r['citations'])})")
    return "\n".join(L) + "\n"


