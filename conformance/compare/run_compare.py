def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--golden-port", type=int, default=8290)
    ap.add_argument("--db-dir", default="/tmp/ucp_p2cmp_golden")
    ap.add_argument("--proxy-port", type=int, default=8291)
    ap.add_argument("--sim-secret", default="selfcheck-secret")
    ap.add_argument("--repeat", type=int, default=2,
                    help="runs per suite per mutant; catch requires ALL repeats to catch")
    ap.add_argument("--baseline-repeat", type=int, default=2)
    ap.add_argument("--only", help="comma-separated mutant ids (debugging; final results must be a full run)")
    ap.add_argument("--out", default=str(HERE / "results"))
    args = ap.parse_args()

    spec = json.loads((HERE / "mutants.json").read_text())
    mutants = spec["mutants"]
    if args.only:
        keep = set(args.only.split(","))
        mutants = [m for m in mutants if m["id"] in keep]

    problems, _ = validate_citations(mutants, ROOT / "conformance" / "requirements" / "2026-04-08")
    if problems:
        print("CITATION PROBLEMS:\n  " + "\n  ".join(problems), file=sys.stderr)
        return 1

    # our canonical flower config — imported, not duplicated
    sys.path.insert(0, str(SELF)); sys.path.insert(0, str(CHECKS))
    from validate_merchant_checks import REF_CONFIG           # noqa: E402
    cfg_path = pathlib.Path(tempfile.gettempdir()) / "p2cmp_flower_config.json"
    cfg_path.write_text(json.dumps(REF_CONFIG, indent=2))

    if not OFFICIAL_DIR.is_dir():
        print(f"official suite not present at {OFFICIAL_DIR} — run fetch_official.sh", file=sys.stderr)
        return 1
    for port in (args.proxy_port, args.golden_port):
        if not _port_free(port):
            print(f"port {port} busy — refusing (same reasoning as serve_golden.sh)", file=sys.stderr)
            return 1

    # Provenance guard: results committed as THE results must be attributable to
    # a clean, reachable commit — "valid only for the pins in its meta block"
    # (README) is self-defeating if the pin is a dirty tree. Debug runs go to a
    # non-default --out; the default results/ requires a clean tree.
    tree_dirty = bool(subprocess.run(["git", "-C", str(ROOT), "status", "--porcelain"],
                                     capture_output=True, text=True).stdout.strip())
    if tree_dirty and pathlib.Path(args.out).resolve() == (HERE / "results").resolve():
        print("working tree is dirty — refusing to write the canonical results/ "
              "(commit first, or use --out elsewhere for a debug run)", file=sys.stderr)
        return 1

    golden = Golden(args.golden_port, args.sim_secret, args.db_dir)
    proxy_url = f"http://localhost:{args.proxy_port}"
    dirty = bool(subprocess.run(["git", "-C", str(ROOT), "status", "--porcelain"],
                                capture_output=True, text=True).stdout.strip())
    results = {"meta": {
        "timestamp": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "pins": {
            "spck_repo": subprocess.run(["git", "-C", str(ROOT), "rev-parse", "HEAD"],
                                        capture_output=True, text=True).stdout.strip()
                         + ("+dirty" if dirty else ""),
            "official_conformance": subprocess.run(["git", "-C", str(OFFICIAL_DIR), "rev-parse", "HEAD"],
                                                   capture_output=True, text=True).stdout.strip(),
            "official_python_sdk": subprocess.run(["git", "-C", str(PYSDK_DIR), "rev-parse", "HEAD"],
                                                  capture_output=True, text=True).stdout.strip(),
            "golden_samples": json.loads((ROOT / "conformance" / "SOURCES.lock.json").read_text()
                                         )["reference_sample_server"]["commit"],
        },
        "repeat": args.repeat, "golden": golden.url,
        "fresh_golden_per_suite_run": True,
    }}

    def spck_on_fresh_golden(mutant=None):
        """One spck run against a freshly reseeded golden (through the proxy)."""
        golden.boot()
        p = start_proxy(golden.url, args.proxy_port, mutant)
        try:
            return run_spck(proxy_url, cfg_path)
        finally:
            p.kill(); p.wait(); golden.stop()

    def official_on_fresh_golden(mutant=None):
        """One official-suite run against a freshly reseeded golden (through the proxy)."""
        golden.boot()
        p = start_proxy(golden.url, args.proxy_port, mutant)
        try:
            return run_official(proxy_url, args.sim_secret)
        finally:
            p.kill(); p.wait(); golden.stop()

    # ---------------- baselines (passthrough proxy) ----------------
    # Both suites get the SAME baseline treatment: --baseline-repeat runs each,
    # anything red in some-but-not-all baseline runs is unstable and earns no
    # catch credit for that suite. (A single spck baseline would have meant no
    # spck check could ever be flagged flaky — a structural asymmetry.)
    print("== baseline (passthrough proxy; fresh golden per run) ==", flush=True)
    spck_runs = []
    for i in range(args.baseline_repeat):
        d, m = spck_on_fresh_golden()
        if d is None:
            print("spck baseline crashed:\n" + m.get("stderr", ""), file=sys.stderr)
            return 1
        spck_runs.append((d, m))
        print(f"  spck baseline #{i + 1}: aggregate={m['aggregate']} "
              f"musts_passed={m['musts_passed']} deviations={m['deviation_musts']}", flush=True)
    base_meta = spck_runs[0][1]
    base_devs = sorted(set.intersection(*(set(d) for d, _ in spck_runs)))
    spck_unstable = sorted(set.union(*(set(d) for d, _ in spck_runs)) - set(base_devs))
    off_runs = []
    for i in range(args.baseline_repeat):
        f, meta = official_on_fresh_golden()
        if f is None:
            print("official baseline crashed:\n" + meta.get("stderr", ""), file=sys.stderr)
            return 1
        off_runs.append((f, meta))
        print(f"  official baseline #{i + 1}: {meta['failures']} failed, "
              f"{meta['errors']} errors, {meta['skipped']} skipped of {meta['tests']}", flush=True)
    base_off_failed = sorted(set.intersection(*(set(f) for f, _ in off_runs)))
    unstable = sorted(set.union(*(set(f) for f, _ in off_runs)) - set(base_off_failed))
    results["baseline"] = {"spck": base_meta, "spck_deviations": base_devs,
                           "spck_unstable": spck_unstable,
                           "official": off_runs[0][1], "official_failed": base_off_failed,
                           "official_unstable": unstable}

    # ---------------- mutants ----------------
    out_mutants, records = [], {}
    for mu in mutants:
        print(f"== mutant {mu['id']} ({mu['mutate']}) ==", flush=True)
        s_catches, s_new, s_crashed = [], [], False
        o_catches, o_new, o_crashed = [], [], False
        for rep in range(args.repeat):
            devs, smeta = spck_on_fresh_golden(mu)
            if devs is None:
                s_crashed = True; s_catches.append(False)
            else:
                c, new = decide_catch_spck(sorted(set(base_devs) | set(spck_unstable)),
                                           devs, False)
                s_catches.append(c); s_new = new
            fails, ometa = official_on_fresh_golden(mu)
            if fails is None:
                o_crashed = True; o_catches.append(False)
            else:
                c, new = decide_catch_official(unstable, base_off_failed, fails, False)
                o_catches.append(c); o_new = new
            print(f"  repeat {rep + 1}: spck={'CATCH' if s_catches[-1] else 'miss'} "
                  f"official={'CATCH' if o_catches[-1] else 'miss'}", flush=True)
        rec = {
            "id": mu["id"], "defect": mu["defect"], "mutate": mu["mutate"],
            "citations": mu["citations"], "shared_surface": bool(mu.get("shared_surface")),
            "diagnostic": bool(mu.get("diagnostic")),
            "surface_note": mu.get("surface_note", ""),
            "spck_catch": all(s_catches), "spck_new_deviations": s_new,
            "spck_crashed": s_crashed,
            "official_catch": all(o_catches), "official_new_failures": o_new,
            "official_crashed": o_crashed,
            "deterministic": (len(set(s_catches)) == 1 and len(set(o_catches)) == 1),
        }
        out_mutants.append(rec)
        records[mu["id"]] = {"spck_catch": rec["spck_catch"],
                             "official_catch": rec["official_catch"]}
    results["mutants"] = out_mutants
    results["rates"] = compute_rates(mutants, records)

    out = pathlib.Path(args.out); out.mkdir(parents=True, exist_ok=True)
