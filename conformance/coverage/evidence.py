#!/usr/bin/env python3
"""
evidence.py — the EVIDENCE-CLASS layer of the coverage matrix (honest accounting of
WHAT KIND of evidence stands behind each CHECK-bucket id).

The matrix's CHECK bucket says "a shipped check cites this MUST" — it deliberately
says nothing about how strong that check's evidence is. A check kill-tested live
against an independently-authored server, a fixture validated through the official
ucp-schema oracle, a self-signed crypto self-test, and a hand-written predicate over
our own fixture all bucket identically. That conflation is exactly the
fixture-circularity class we flag upstream (conformance#79), so this layer names it
in our own accounting. It is REPORTING ONLY: it never changes which ids bucket as
CHECK, never weakens a check, and never moves a ratchet/lock number.

Every check object is classified MECHANICALLY — from how it actually runs, never a
hand label:

  live-wire       the check probes a live server over the wire AND the committed
                  reach report (reach_report.json, generated by gen_reach_report.py
                  from an actual run against the independent differential targets)
                  shows it GRADED (clean-pass or deviation) on at least one server
                  we did not author (flower golden / node reference).
  fixture-schema  the check's target is a local fixture/synthetic instance whose
                  verdict comes from the OFFICIAL ucp-schema oracle — anchored to
                  the pinned spec, not to our own reading of it.
  fixture-crypto  the check's target is a local fixture and its verdict comes from
                  our own crypto primitives over a self-signed key (e.g. the AP2
                  _MERCHANT_SEED checks) — a primitive self-test, spec-shaped but
                  not independently corroborated.
  self-referenced the genuine fixture-circularity class: EITHER a wire-probing
                  check that has never graded an independent target (it only ever
                  runs against our own fixture server), OR a local-fixture check
                  whose verdict comes from our own hand-written predicate with no
                  independent oracle. FAIL-CLOSED default: anything the mechanics
                  cannot positively place in a stronger class lands here (a missing
                  reach report demotes every wire check to self-referenced — the
                  layer can under-claim, never over-claim).
  register-selfcheck  (A3, D1-13) a STRUCT check (struct_check_08_25: pure `fn` over
                  `valid`/`negatives` cases, no target at all) whose verdict is a fact
                  about the PINNED CORPUS itself: its fn, or a case it is fed, reaches
                  by identity an object in struct_check_08_25.CORPUS_DOCS (the vendored
                  schema documents and what is extracted from them verbatim) — e.g.
                  "capability.json requires `schema` on business_schema". Not
                  target-facing: it grades the spec text, never an implementation.
  reference-impl  (A3, D1-13) a struct check with NO corpus reach: OUR implementation
                  of an algorithm the prose fixes (the permalink codec, the unit_price
                  comparator, authority binding, URL-fetch safety), proven against our
                  own fixtures. FAIL-CLOSED default for the struct kind — a plain
                  predicate can never classify register-selfcheck.

Mechanics (no hand labels anywhere):
  * acquisition: an MCheck (duck-typed by its `cfg_needs` attribute) is always
    graded via a MerchantCtx built from a live server, so it is wire by
    construction. An engine Check is wire iff its fetch_fn TRANSITIVELY reaches a
    network entrypoint (engine.fetch/mcp_call/mcp_call_raw/a2a_call, or a stdlib
    net module) — the schema_check.py fixture lambdas ignore `base` and reach only
    the fixture loader, so they classify fixture. A schema-tier namedtuple check
    (duck-typed by its `schema_rel` field) is by construction a fixture validated
    through the official oracle.
  * oracle (fixture tier): the predicate's transitive reach decides — schema_oracle
    (or a predicate closed over inside schema_check.py, where schema_predicate
    builds it) => fixture-schema; the crypto/nested primitive modules =>
    fixture-crypto; neither => self-referenced.
  * corroboration (wire tier): reach_report.json, keyed "version:module_stem:
    check_id" (the VERSION AXIS — R4/W1a: a check graded against a target that
    served spec version V is corroboration for THAT version only. A check
    scoped to several versions but graded against a target serving only one of
    them earns live-wire at that version alone; the others fail closed to
    self-referenced until a run actually grades them there too. Without this
    axis a single 04-08 differential run silently "corroborates" every OTHER
    version the same check object happens to be attributed to — proven live on
    2026-08-31: the committed report has only ever graded 2026-04-08, yet
    before this fix 2026-01-11/2026-01-23 published nonzero live-wire counts,
    and lifting the 2026-08-25 register-only wall would have handed 26 checks
    live-wire credit for a version with zero independently-authored
    implementation.) generated ONLY from servers listed in
    ci/differential_targets.json (the independent-target register), merged
    into the committed report per (target, served-version) SLICE — see
    gen_reach_report.py's module docstring for why a whole-file overwrite
    would make multi-version corroboration mutually erase itself.

Kill-tested by conformance/selfcheck/validate_evidence_class.py (--selftest): a
classifier that mislabels any representative check, skips transitive reach, or
grants live-wire without reach evidence goes red there.
"""
import json
import os
import types

HERE = os.path.dirname(os.path.abspath(__file__))
CONF = os.path.dirname(HERE)                       # conformance/
REACH_FILE = os.path.join(HERE, "reach_report.json")

# discovery-live (D4-08, decision 4): a check whose predicate reads a discovery-live CAPTURE
# (conformance/ci/discovery_live.load_capture — a real store's GET /.well-known/ucp, sampled on
# the owner's machine under probe_policy.json) and whose entry in coverage/discovery_reach.json
# shows >= 3 distinct domains graded within 30 days. Ranked below live-wire and NEVER promoted
# to it: a discovery capture is one read of one public document, not an independent
# implementation the differential gate probes (differential_targets.json stays at 2).
# W1 integration: the seven classes = D4-08's discovery tier + D1-13's two A3 classes.
CLASSES = ("live-wire", "discovery-live", "fixture-schema", "fixture-crypto", "self-referenced",
           "register-selfcheck", "reference-impl")
# the five TARGET-FACING classes (a live server, a real store's published document, or a
# fixture instance was graded); the two A3 classes grade the corpus / our own algorithm —
# matrix.integrity splits on this
TARGET_FACING = ("live-wire", "discovery-live", "fixture-schema", "fixture-crypto", "self-referenced")
# strongest-first rank for per-id aggregation (an id covered by several checks gets
# the strongest evidence any of them provides): every target-facing class outranks the
# corpus self-check, which outranks our own algorithm's self-proof.
_RANK = {"live-wire": 6, "discovery-live": 5, "fixture-schema": 4, "fixture-crypto": 3,
         "self-referenced": 2, "register-selfcheck": 1, "reference-impl": 0}
DISCOVERY_REACH_FILE = os.path.join(HERE, "discovery_reach.json")
_DISCOVERY_MODULES = ("discovery_live",)

# network entrypoints: the engine's wire functions by NAME (resolved by identity in
# _reaches, so a same-named local helper can't spoof them) + stdlib net modules.
_WIRE_FUNCS = ("fetch", "mcp_call", "mcp_call_raw", "a2a_call")
_NET_MODULE_PREFIXES = ("urllib", "http.client", "socket", "ssl")
_ORACLE_SCHEMA_MODULES = ("schema_oracle",)
_ORACLE_CRYPTO_MODULES = ("crypto", "nested")


def _engine_wire_funcs():
    """Resolve the engine's wire entrypoints to their live function objects (identity
    anchors for _reaches). Lazy so importing evidence.py never drags the engine in
    for consumers that only need load_reach()."""
    import sys
    chk_dir = os.path.join(CONF, "checks")
    if chk_dir not in sys.path:
        sys.path.insert(0, chk_dir)
    import engine
    return {getattr(engine, n) for n in _WIRE_FUNCS if hasattr(engine, n)}


def _code_objects(fn):
    """The function's code object plus every nested code const (lambdas, closures)."""
    co = getattr(fn, "__code__", None)
    if co is None:
        return
    stack = [co]
    while stack:
        c = stack.pop()
        yield c
        for k in c.co_consts:
            if isinstance(k, types.CodeType):
                stack.append(k)


def _referenced_objects(fn):
    """(objects, names): objects a function can call/read — resolved global names +
    closure cells + default arguments — and every name its code references
    (co_names covers both globals AND attribute accesses like `engine.fetch`).
    Purely mechanical — no name lists beyond the code object."""
    out = []
    g = getattr(fn, "__globals__", {}) or {}
    names = set()
    for co in _code_objects(fn):
        names |= set(co.co_names)
    out += [g[n] for n in names if n in g]
    for cell in (getattr(fn, "__closure__", None) or ()):
        try:
            out.append(cell.cell_contents)
        except ValueError:
            pass
    out += list(getattr(fn, "__defaults__", None) or ())
    return out, names


def _reaches(fn, target_funcs=frozenset(), module_prefixes=(), _seen=None, _depth=0):
    """True iff `fn` TRANSITIVELY references one of `target_funcs` (by identity —
    either as a direct `from engine import fetch` global, or as an attribute of a
    referenced module, e.g. `engine.fetch(...)`) or any module/function whose
    module name starts with one of `module_prefixes`. Recurses only into callables
    defined under conformance/ (our own helpers), so a fixture check that merely
    uses json/pathlib never false-positives."""
    if _seen is None:
        _seen = set()
    if _depth > 8 or not callable(fn):
        return False
    objs, names = _referenced_objects(fn)
    for obj in objs:
        if callable(obj) and any(obj is t for t in target_funcs):
            return True
        if isinstance(obj, types.ModuleType):
            # `mod.func(...)` pattern: the module arrives via global/closure and the
            # function name via LOAD_ATTR (co_names) — resolve it by identity too.
            if any(getattr(obj, n, None) is t for n in names for t in target_funcs):
                return True
        mod = obj.__name__ if isinstance(obj, types.ModuleType) \
            else getattr(obj, "__module__", None) or ""
        if mod and any(mod == p or mod.startswith(p + ".") for p in module_prefixes):
            return True
        if callable(obj):
            co = getattr(obj, "__code__", None)
            if co is None or id(co) in _seen:
                continue
            _seen.add(id(co))
            if co.co_filename.startswith(CONF) and \
                    _reaches(obj, target_funcs, module_prefixes, _seen, _depth + 1):
                return True
    return False


def _reaches_file(fn, basenames, _seen=None, _depth=0):
    """True iff `fn` TRANSITIVELY references a function DEFINED in one of `basenames`
    (compared by code-object filename, so a module executed as __main__ — e.g.
    discovery_live.py --selftest — is recognised exactly like `import discovery_live`)."""
    if _seen is None:
        _seen = set()
    if _depth > 8 or not callable(fn):
        return False
    objs, _names = _referenced_objects(fn)
    for obj in objs:
        co = getattr(obj, "__code__", None)
        if co is None:
            continue
        if os.path.basename(co.co_filename) in basenames:
            return True
        if id(co) in _seen:
            continue
        _seen.add(id(co))
        if co.co_filename.startswith(CONF) and _reaches_file(obj, basenames, _seen, _depth + 1):
            return True


def _corpus_docs():
    """struct_check_08_25.CORPUS_DOCS resolved lazily (identity anchors for the
    register-selfcheck class); () when the module is absent — fail-closed: every struct
    check then classifies reference-impl."""
    import sys
    chk_dir = os.path.join(CONF, "checks")
    if chk_dir not in sys.path:
        sys.path.insert(0, chk_dir)
    try:
        import struct_check_08_25
        return tuple(struct_check_08_25.CORPUS_DOCS)
    except (ImportError, AttributeError):
        return ()


def _walk_values(obj, _depth=0):
    """Yield obj and, for tuples/lists/dicts, every nested value (case args can wrap a
    corpus document in a tuple)."""
    yield obj
    if _depth > 4:
        return
    if isinstance(obj, (list, tuple)):
        for x in obj:
            yield from _walk_values(x, _depth + 1)
    elif isinstance(obj, dict):
        for x in obj.values():
            yield from _walk_values(x, _depth + 1)


def corpus_reach(chk, docs=None):
    """True iff a struct check's verdict reaches the pinned corpus BY IDENTITY: its `fn`
    (transitively, through our own helpers) references a CORPUS_DOCS object, or one of
    its `valid` cases feeds one in. Equality is never enough — a copied dict is not the
    corpus (a plain predicate over plain fixtures stays reference-impl)."""
    docs = _corpus_docs() if docs is None else tuple(docs)
    if not docs:
        return False

    def hits(obj):
        return any(obj is d for d in docs)
    for case in (getattr(chk, "valid", None) or ()):
        if any(hits(v) for v in _walk_values(case)):
            return True
    seen = set()
    stack = [getattr(chk, "fn", None)]
    depth = 0
    while stack and depth < 200:
        depth += 1
        fn = stack.pop()
        if not callable(fn):
            continue
        co = getattr(fn, "__code__", None)
        if co is None or id(co) in seen:
            continue
        seen.add(id(co))
        objs, _names = _referenced_objects(fn)
        for obj in objs:
            if hits(obj):
                return True
            if callable(obj) and getattr(obj, "__code__", None) is not None \
                    and obj.__code__.co_filename.startswith(CONF):
                stack.append(obj)
    return False


def acquisition(chk):
    """How the check OBTAINS its graded response: 'wire' (live server), 'fixture'
    (local synthetic target), 'schema-tier' (namedtuple checks whose runner IS
    the official schema oracle) or 'struct' (a pure fn over valid/negative cases —
    no target at all, A3). Mechanical — see module docstring."""
    if hasattr(chk, "schema_rel"):
        return "schema-tier"
    if hasattr(chk, "negatives") and hasattr(chk, "valid") and hasattr(chk, "fn") \
            and not hasattr(chk, "predicate"):
        return "struct"
    if hasattr(chk, "cfg_needs"):
        # MCheck: graded exclusively via run_merchant_checks(MerchantCtx(live server))
        # — even a fetch_fn that only reads ctx.profile reads data fetched from the
        # live target by discover().
        return "wire"
    fetch_fn = getattr(chk, "fetch_fn", None)
    if fetch_fn is not None and _reaches(fetch_fn, _engine_wire_funcs(),
                                         _NET_MODULE_PREFIXES):
        return "wire"
    return "fixture"


def _fixture_oracle(chk):
    """For a fixture-acquiring check: which independent oracle (if any) produces the
    verdict. 'schema' | 'crypto' | None."""
    pred = getattr(chk, "predicate", None)
    if pred is None:
        return None
    # schema_predicate() builds the predicate inside schema_check.py — the closure's
    # own filename is the mechanical fingerprint of the oracle path.
    co = getattr(pred, "__code__", None)
    if co is not None and os.path.basename(co.co_filename) == "schema_check.py":
        return "schema"
    if _reaches(pred, module_prefixes=_ORACLE_SCHEMA_MODULES):
        return "schema"
    if _reaches(pred, module_prefixes=_ORACLE_CRYPTO_MODULES):
        return "crypto"
    return None


def reach_key(version, module_stem, chk):
    """The reach-report key for one (spec version, check) pair — VERSION FIRST so
    a key prefix (`f"{version}:"`) cleanly names one whole slice, the same shape
    gen_reach_report.py's per-(target,version) merge groups by."""
    return f"{version}:{module_stem}:{chk.id}"


def load_reach(path=REACH_FILE):
    """{reach_key: sorted[target names GRADED on]} from the committed reach report.
    Missing/unreadable file => {} (every wire check demotes to self-referenced —
    fail-closed, the layer under-claims rather than fabricating corroboration)."""
    try:
        d = json.load(open(path))
    except Exception:
        return {}
    out = {}
    for key, entry in (d.get("checks") or {}).items():
        graded = sorted(t for t, st in (entry.get("targets") or {}).items()
                        if st in ("clean-pass", "deviation"))
        if graded:
            out[key] = graded
    return out


def load_discovery_reach(path=DISCOVERY_REACH_FILE):
    """{check_id: {domains, latest}} from the committed discovery_reach.json (rows are keyed
    by req id there; a check earns via any of its req_ids). Missing file => {} (fail-closed:
    every capture-reading check demotes to self-referenced)."""
    try:
        d = json.load(open(path))
    except Exception:
        return {}
    return d.get("rows") or {}


def _discovery_row(chk, discovery_reach):
    """The strongest discovery_reach row for this check: by check id, else by any req id."""
    if not discovery_reach:
        return None
    if chk.id in discovery_reach:
        return discovery_reach[chk.id]
    best = None
    for rid in (getattr(chk, "req_ids", None) or []):
        row = discovery_reach.get(rid)
        if row and (best is None or row.get("domains", 0) > best.get("domains", 0)):
            best = row
    return best


def _discovery_live(row):
    import datetime
    if not row or not row.get("latest"):
        return False
    try:
        age = (datetime.date.today() - datetime.date.fromisoformat(row["latest"])).days
    except ValueError:
        return False
    return int(row.get("domains", 0)) >= 3 and age <= 30


def classify_check(chk, module_stem, version, reach=None, discovery_reach=None):
    """(evidence_class, graded_independent_targets) for one check object AT one
    spec version. `version` is load-bearing for the wire tier ONLY: a check
    graded against a target serving spec V corroborates V, never a sibling
    version the same check object also happens to be attributed to (R4 — the
    reach report is keyed per-version precisely so this call can't cross-credit).
    A check whose predicate/fetch reaches discovery_live.load_capture is the DISCOVERY tier
    (D4-08): discovery-live with >= 3 domains within 30 days, else self-referenced — never
    live-wire, whatever the reach report says."""
    reach = {} if reach is None else reach
    fn = getattr(chk, "predicate", None) or getattr(chk, "fetch_fn", None)
    if fn is not None and (_reaches(fn, module_prefixes=_DISCOVERY_MODULES)
                           or _reaches_file(fn, ("discovery_live.py",))):
        dr = load_discovery_reach() if discovery_reach is None else discovery_reach
        return ("discovery-live" if _discovery_live(_discovery_row(chk, dr)) else "self-referenced"), []
    acq = acquisition(chk)
    if acq == "schema-tier":
        return "fixture-schema", []
    if acq == "struct":
        return ("register-selfcheck" if corpus_reach(chk) else "reference-impl"), []
    if acq == "wire":
        targets = reach.get(reach_key(version, module_stem, chk), [])
        return ("live-wire" if targets else "self-referenced"), list(targets)
    oracle = _fixture_oracle(chk)
    if oracle == "schema":
        return "fixture-schema", []
    if oracle == "crypto":
        return "fixture-crypto", []
    return "self-referenced", []


def strongest(classes):
    """The strongest evidence class in `classes` (per-id aggregation)."""
    classes = [c for c in classes if c in _RANK]
    if not classes:
        return "self-referenced"
    return max(classes, key=lambda c: _RANK[c])


def evidence_by_id(attribution_rows, reach=None):
    """{version: {req_id: {"evidence": strongest_class, "reach": sorted targets}}}
    from matrix.attribution() rows — the same walk coverage_map() uses, so the
    evidence layer can never disagree with the CHECK bucket. A text-scan fallback
    row (check object None) contributes self-referenced (fail-closed).

    The classification cache is keyed by (id(chk), version) — NOT id(chk) alone —
    because classify_check()'s wire tier is version-sensitive (R4): the same check
    object attributed to two versions can legitimately classify differently (e.g.
    live-wire at the one version a reach-report run actually graded it against,
    self-referenced at a sibling version no run has graded yet)."""
    if reach is None:
        reach = load_reach()
    cache = {}          # (id(chk), version) -> (class, targets)
    out = {}
    for version, rid, basename, chk in attribution_rows:
        if chk is None:
            cls, targets = "self-referenced", []
        else:
            key = (id(chk), version)
            if key not in cache:
                stem = os.path.splitext(basename)[0]
                cache[key] = classify_check(chk, stem, version, reach)
            cls, targets = cache[key]
        # the slot starts EMPTY (D1-13): seeding it with self-referenced would outrank
        # the two A3 classes and hide every struct check behind the fail-closed label
        slot = out.setdefault(version, {}).setdefault(rid, {"evidence": None, "reach": set()})
        slot["evidence"] = strongest([c for c in (slot["evidence"], cls) if c])
        slot["reach"] |= set(targets)
    for m in out.values():
        for slot in m.values():
            slot["reach"] = sorted(slot["reach"])
    return out


def breakdown(evidence_map, version, ids):
    """{class: count} over `ids` (the CHECK-bucket MUST ids of `version`)."""
    counts = {c: 0 for c in CLASSES}
    for rid in ids:
        cls = (evidence_map.get(version, {}).get(rid) or {}).get("evidence",
                                                                 "self-referenced")
        counts[cls] += 1
    return {c: n for c, n in counts.items()}


def integrity(bd):
    """{target_facing, corpus, algorithm} from a breakdown (D1-13): what KIND of thing
    each CHECK id's strongest evidence graded — an implementation (target-facing), the
    pinned spec text (corpus) or our own algorithm (algorithm). Partitions CHECK."""
    return {"target_facing": sum(bd.get(c, 0) for c in TARGET_FACING),
            "corpus": bd.get("register-selfcheck", 0),
            "algorithm": bd.get("reference-impl", 0)}
